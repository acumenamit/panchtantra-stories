// Builds the committed fixtures catalogue for fixtures mode (spec §3.2; owner decision D1, 2026-11-13):
//   pnpm fixtures:catalogue
// Reads every fixtures/packages/*.json and writes, as canonical JCS bytes from the catalogue builders:
//   fixtures/catalogue/fixtures.json        the pointer
//   fixtures/catalogue/snapshots/1.json     the snapshot, naming each package by sha256(file bytes)
// Timestamps are fixed, so the same packages always give the same bytes. A unit test fails, naming
// this script, when the committed files no longer match the packages.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import type { SnapshotEntry } from '../src/core/content/packages'
import { sha256Hex } from '../src/core/hashing'
import {
  makePointer,
  makeSnapshot,
  pointerPath,
  snapshotPath,
} from '../src/core/package/catalogue-build'
import { StoryPackageV1 } from '../src/core/package/v1'
import { isEntryPoint } from './load-content'

export const FIXTURES_SEQ = 1
/** Fixed, so the bytes never depend on when the script ran. */
export const FIXTURES_TIMESTAMP = '2026-11-13T00:00:00.000Z'
export const FIXTURES_NOTE =
  'Synthetic fixtures for CI and local builds; generated by scripts/build-fixtures-catalogue.ts'

export interface CatalogueFile {
  /** Relative to fixtures/, with '/' separators. */
  readonly path: string
  readonly bytes: Uint8Array<ArrayBuffer>
}

/** One snapshot entry per fixtures/packages/*.json, sorted by file name; each must strict-parse. */
export async function readFixtureEntries(fixturesDir: string): Promise<SnapshotEntry[]> {
  const packagesDir = join(fixturesDir, 'packages')
  const names = readdirSync(packagesDir)
    .filter((name) => name.endsWith('.json'))
    .sort()
  const entries: SnapshotEntry[] = []
  for (const name of names) {
    const bytes = new Uint8Array(readFileSync(join(packagesDir, name)))
    const pkg = StoryPackageV1.parse(JSON.parse(new TextDecoder().decode(bytes)))
    entries.push({
      storyId: pkg.storyId,
      collectionId: pkg.collectionId,
      version: pkg.version,
      packagePath: `packages/${name}`,
      packageSha256: await sha256Hex(bytes),
    })
  }
  return entries
}

/** The pointer and snapshot for these entries: seq 1, fixed timestamps, no approvals. */
export async function buildCatalogue(
  stories: readonly SnapshotEntry[],
  featuredStoryId: string | null = null,
): Promise<CatalogueFile[]> {
  const snapshot = await makeSnapshot({
    schemaVersion: '1.0',
    seq: FIXTURES_SEQ,
    createdAt: FIXTURES_TIMESTAMP,
    note: FIXTURES_NOTE,
    featuredStoryId,
    stories: [...stories],
  })
  const pointer = await makePointer({
    schemaVersion: '1.0',
    seq: FIXTURES_SEQ,
    snapshotPath: snapshotPath(FIXTURES_SEQ),
    snapshotSha256: snapshot.sha256,
    updatedAt: FIXTURES_TIMESTAMP,
  })
  return [
    { path: pointerPath('fixtures'), bytes: pointer.bytes },
    { path: snapshotPath(FIXTURES_SEQ), bytes: snapshot.bytes },
  ]
}

/** The catalogue the committed packages call for, with featuredStoryId null. */
export async function buildFixturesCatalogue(fixturesDir: string): Promise<CatalogueFile[]> {
  return buildCatalogue(await readFixtureEntries(fixturesDir))
}

/** Replaces fixtures/catalogue/ with exactly these files, so no stale snapshot is left behind. */
export function writeCatalogue(fixturesDir: string, files: readonly CatalogueFile[]): void {
  rmSync(join(fixturesDir, 'catalogue'), { recursive: true, force: true })
  for (const file of files) {
    const target = join(fixturesDir, ...file.path.split('/'))
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, file.bytes)
  }
}

async function main(): Promise<number> {
  const fixturesDir = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'fixtures')
  const files = await buildFixturesCatalogue(fixturesDir)
  writeCatalogue(fixturesDir, files)
  for (const file of files) {
    const sha = (await sha256Hex(file.bytes)).slice(0, 12)
    console.log(`fixtures: wrote fixtures/${file.path} sha=${sha}`)
  }
  return 0
}

if (isEntryPoint(import.meta.url, process.argv[1])) {
  main().then(
    (code) => process.exit(code),
    (error: unknown) => {
      console.error(`fixtures: ${error instanceof Error ? error.message : 'unknown error'}`)
      process.exit(1)
    },
  )
}
